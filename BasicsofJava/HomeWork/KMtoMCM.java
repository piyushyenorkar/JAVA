package BasicsofJava.HomeWork;

public class KMtoMCM {
    public static void main(String[] args){
        double km = 6.0;
        double m = km * 1000;
        double cm = m * 100;
        System.out.println("Distance in meters: " + m);
        System.out.println("Distance in centimeters: " + cm);
    }
}
